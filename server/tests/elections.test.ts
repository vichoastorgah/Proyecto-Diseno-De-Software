Deno.test("elections: adding voters refuses duplicates and closed elections; resend rotates the link", async () => {
  const env = await createTestEnv();
  try {
    const token = await env.sessionFor(ADMIN);
    const created = await env.request("POST", "/api/admin/elections", { token, form: electionForm() });
    const id = created.body.electionId as string;

    const duplicate = new FormData();
    duplicate.set("votersCsv", csvFile("email,name,birthdate,gender,weight\nana@example.com,Ana,1990-01-01,f,1\n"));
    const conflict = await env.request("POST", `/api/admin/elections/${id}/voters`, { token, form: duplicate });
    assertEquals([conflict.status, conflict.body.code], [409, "VOTERS_ALREADY_EXIST"]);

    const extra = new FormData();
    extra.set("votersCsv", csvFile("email,name,birthdate,gender,weight\ndiego@example.com,Diego,1991-01-01,m,4\n"));
    const added = await env.request("POST", `/api/admin/elections/${id}/voters`, { token, form: extra });
    assertEquals([added.status, added.body.imported], [201, 1]);

    const voters = await env.request("GET", `/api/admin/elections/${id}/voters?search=diego`, { token });
    const diego = (voters.body.items as { id: number; email: string }[])[0];
    assertEquals(diego.email, "diego@example.com");
    assertEquals(voters.body.total, 1);

    const oldToken = tokenFromEmail(env, "diego@example.com");
    const resend = await env.request("POST", `/api/admin/elections/${id}/voters/${diego.id}/resend`, { token });
    assertEquals(resend.status, 200);
    const newToken = tokenFromEmail(env, "diego@example.com");
    assertNotEquals(oldToken, newToken);
    assertEquals((await env.request("GET", `/api/vote/context?token=${oldToken}`)).status, 404);
    assertEquals((await env.request("GET", `/api/vote/context?token=${newToken}`)).status, 200);

    const closed = await env.request("POST", `/api/admin/elections/${id}/status`, { token, json: { status: "closed" } });
    assertEquals(closed.body.status, "closed");
    const afterClose = new FormData();
    afterClose.set("votersCsv", csvFile("email,name,birthdate,gender,weight\neve@example.com,Eve,1991-01-01,f,1\n"));
    const refused = await env.request("POST", `/api/admin/elections/${id}/voters`, { token, form: afterClose });
    assertEquals([refused.status, refused.body.code], [409, "ELECTION_CLOSED"]);
  } finally {
    await env.cleanup();
  }
});

