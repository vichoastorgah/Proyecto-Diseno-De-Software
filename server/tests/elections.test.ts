import { assert, assertEquals, assertMatch, assertNotEquals } from "@std/assert";
import { ADMIN, createTestEnv, csvFile, electionForm, PDF_BYTES, tokenFromEmail, VALID_CSV } from "./testUtils.ts";

type Detail = { code: string; row?: number };

Deno.test("elections: create with several motions, attachment and personalized emails", async () => {
  const env = await createTestEnv();
  try {
    const token = await env.sessionFor(ADMIN);
    const created = await env.request("POST", "/api/admin/elections", { token, form: electionForm() });
    assertEquals(created.status, 201);
    assertEquals(created.body.imported, 3);
    assertEquals(created.body.emailsSent, 3);
    assertEquals(created.body.deliveryMode, "simulated");

    // Personalized by name and gender, with the attachment and a unique link.
    const ana = env.mailer.sent.find((mail) => mail.to === "ana@example.com")!;
    assertMatch(ana.text, /Dear Ms\. Ana Test/);
    assertMatch(ana.text, /Approve the budget/);
    assertMatch(ana.text, /Elect the board/);
    assertEquals(ana.attachments.map((file) => file.filename), ["budget.pdf"]);
    const bruno = env.mailer.sent.find((mail) => mail.to === "bruno@example.com")!;
    assertMatch(bruno.text, /Dear Mr\. Bruno Test/);
    const tokens = ["ana@example.com", "bruno@example.com", "carla@example.com"].map((email) => tokenFromEmail(env, email));
    assertEquals(new Set(tokens).size, 3);

    // Tokens are stored hashed, never in clear text.
    const stored = await env.db.all<{ token_hash: string }>("SELECT token_hash FROM voters");
    assert(stored.every((row) => !tokens.includes(row.token_hash)));

    // Stored file name is generated by the server.
    const files = [...Deno.readDirSync(env.config.uploadsDir)].map((entry) => entry.name);
    assertEquals(files.length, 1);
    assertMatch(files[0], /^[0-9a-f-]{36}\.pdf$/);

    const list = await env.request("GET", "/api/admin/elections", { token });
    const elections = list.body.elections as { id: string; stats: { voterCount: number; motionCount: number } }[];
    assertEquals(elections.length, 1);
    assertEquals(elections[0].stats.voterCount, 3);
    assertEquals(elections[0].stats.motionCount, 2);

    const detail = await env.request("GET", `/api/admin/elections/${created.body.electionId}`, { token });
    assertEquals((detail.body.motions as unknown[]).length, 2);
    assertEquals((detail.body.attachments as { name: string }[])[0].name, "budget.pdf");
    assertEquals((detail.body.invitations as Record<string, number>).simulated, 3);

    const download = await env.request(
      "GET",
      `/api/admin/elections/${created.body.electionId}/attachments/${(detail.body.attachments as { id: string }[])[0].id}`,
      { token },
    );
    assertEquals(download.status, 200);
    assertEquals(download.headers.get("content-type"), "application/pdf");
    assertEquals(download.raw, PDF_BYTES);
  } finally {
    await env.cleanup();
  }
});

Deno.test("elections: invalid CSV is rejected with per-row details and nothing is saved", async () => {
  const env = await createTestEnv();
  try {
    const token = await env.sessionFor(ADMIN);
    const csv = "email,name,birthdate,gender,weight\nana@example.com,Ana,1990-01-01,female,1\nana@example.com,,1990-01-01,female,-1\n";
    const response = await env.request("POST", "/api/admin/elections", { token, form: electionForm({ csv }) });
    assertEquals([response.status, response.body.code], [422, "CSV_VALIDATION_FAILED"]);
    const details = response.body.details as Detail[];
    assertEquals(details.map((detail) => detail.code).sort(), ["CSV_DUPLICATE_EMAIL", "CSV_INVALID_NAME", "CSV_INVALID_WEIGHT"]);
    assertEquals((await env.db.all("SELECT id FROM elections")).length, 0);
    assertEquals(env.mailer.sent.length, 0);
  } finally {
    await env.cleanup();
  }
});

